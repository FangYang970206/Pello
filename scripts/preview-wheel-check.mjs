import assert from 'node:assert/strict'
import fs from 'node:fs'
import os from 'node:os'
import path from 'node:path'
import { execFileSync } from 'node:child_process'
import { _electron as electron } from 'playwright'
import { installDocumentHarness, documentCommand } from './fixtures/document-harness.mjs'

const data = fs.mkdtempSync(path.join(os.tmpdir(), 'pello-wheel-'))
const project = path.join(data, 'repo')
fs.mkdirSync(project)
const git = (...args) => execFileSync('git', args, { cwd: project, windowsHide: true })
fs.writeFileSync(path.join(project, 'note.txt'), 'original\n' + 'line\n'.repeat(150))
fs.writeFileSync(path.join(project, 'guide.md'), '# Wheel test\n\nReading text\n\n```js\nconst value = 42\n```\n')
fs.writeFileSync(path.join(project, 'page.html'), '<!doctype html><html><head><title>fixture</title></head><body><h1>HTML wheel</h1><p>Reading text</p></body></html>')
git('init', '-q'); git('add', '.'); git('-c', 'user.name=fixture', '-c', 'user.email=fixture@example.invalid', 'commit', '-qm', 'fixture')
fs.appendFileSync(path.join(project, 'note.txt'), 'changed\n')
const original = fs.readFileSync(path.join(project, 'note.txt'), 'utf8')
fs.writeFileSync(path.join(data, 'workbench.json'), JSON.stringify({ settings: { layout: 'balanced', restore: false, confirmKill: false }, projects: [{ id: 'p', name: 'Wheel test', host: 'local', path: project, agent: 'shell' }] }))
const env = { ...process.env, AWB_USER_DATA: data }; delete env.ELECTRON_RUN_AS_NODE
const app = await electron.launch({ args: ['.'], env })
try {
  const page = await app.firstWindow()
  page.setDefaultTimeout(10000)
  await installDocumentHarness(app, page, false)
  const errors = []; page.on('pageerror', (error) => errors.push(error.message))
  const wheel = async (target, delta = -120, ctrl = true) => {
    await target.hover()
    if (ctrl) await page.keyboard.down('Control')
    try { await page.mouse.wheel(0, delta) } finally { if (ctrl) await page.keyboard.up('Control') }
  }
  const size = (target) => target.evaluate((node) => Number.parseFloat(getComputedStyle(node).fontSize))
  const zoomed = async (target, before, direction = 1) => {
    await target.evaluate((node, { before, direction }) => new Promise((resolve, reject) => {
      const start = performance.now()
      const check = () => {
        if ((Number.parseFloat(getComputedStyle(node).fontSize) - before) * direction > .1) resolve()
        else if (performance.now() - start > 2000) reject(new Error('Ctrl+wheel did not change the content font size'))
        else requestAnimationFrame(check)
      }
      check()
    }), { before, direction })
  }
  await page.click('[data-a=rmode][data-id=files]')
  const open = (name) => page.click(`[data-a=preview][data-id="${name}"]`)
  await open('note.txt')
  const text = page.getByRole('textbox', { name: '文件内容', exact: true })
  await text.fill('unsaved draft\n' + 'line\n'.repeat(150))
  await page.evaluate(() => { window.__sourceNode = document.querySelector('.source-editor textarea') })
  const initial = await size(text)
  await wheel(text); await zoomed(text, initial)
  assert.equal(await page.evaluate(() => window.__sourceNode === document.querySelector('.source-editor textarea')), true)
  const enlarged = await size(text)
  assert.equal(await size(page.locator('.source-highlight')), enlarged, 'Highlight and textarea must stay aligned')
  assert.equal(await size(page.locator('.editor-gutter')), enlarged, 'Gutter must match the source')
  await wheel(text, 120); await zoomed(text, enlarged, -1)
  await wheel(text, 120, false)
  await page.waitForFunction(() => document.querySelector('.source-editor textarea').scrollTop > 0)
  await text.press('Control+z')
  assert.equal(await text.inputValue(), original, 'Zoom must preserve undo history')
  await text.press('Control+Shift+z')
  assert.ok((await text.inputValue()).startsWith('unsaved draft'))

  await open('guide.md')
  const rich = page.getByRole('textbox', { name: 'Markdown 内容', exact: true })
  await rich.waitFor()
  const paragraph = rich.locator('p').first(), heading = rich.locator('h1')
  const richSize = await size(paragraph), headingSize = await size(heading)
  const code = rich.locator('.cm-content').first()
  await code.waitFor()
  const codeSize = await size(code)
  await page.evaluate(() => { window.__richNode = document.querySelector('.ProseMirror') })
  await wheel(paragraph); await zoomed(paragraph, richSize)
  assert.ok(await size(heading) > headingSize)
  assert.ok(await size(code) > codeSize, 'Markdown code must scale with the reading text')
  assert.equal(await page.evaluate(() => window.__richNode === document.querySelector('.ProseMirror')), true)
  await documentCommand(app, page, 'mode')
  await text.waitFor(); const sourceSize = await size(text)
  await wheel(text); await zoomed(text, sourceSize)
  await documentCommand(app, page, 'mode'); await rich.waitFor()
  assert.ok((await rich.textContent()).includes('Reading text'))

  await open('page.html')
  const html = page.frameLocator('iframe').locator('h1')
  await html.waitFor()
  await page.evaluate(() => { window.__frameNode = document.querySelector('iframe') })
  const frameZoom = await page.locator('iframe').evaluate((node) => Number(getComputedStyle(node).zoom))
  await wheel(html)
  await page.waitForFunction((initial) => Number(getComputedStyle(document.querySelector('iframe')).zoom) > initial, frameZoom)
  assert.equal(await page.evaluate(() => window.__frameNode === document.querySelector('iframe')), true, 'HTML zoom must not reload the page')
  assert.equal(await html.evaluate(() => typeof window.awb), 'undefined', 'HTML must remain sandboxed')
  const beforeSpoof = await page.locator('.file-content').getAttribute('style')
  await page.evaluate(() => window.postMessage({ type: 'pello-preview-zoom', deltaY: -120 }, '*'))
  await page.waitForTimeout(100)
  assert.equal(await page.locator('.file-content').getAttribute('style'), beforeSpoof, 'Zoom messages must come from the current iframe')
  await wheel(html, 120)
  await page.waitForFunction((initial) => Number(getComputedStyle(document.querySelector('iframe')).zoom) === initial, frameZoom)

  await page.click('[data-a=rmode][data-id=changes]')
  await page.locator('[data-a=diff][data-id="note.txt"]').click()
  await page.locator('[data-a=dmode][data-id=split]').click()
  const panes = page.locator('.diff-split .cm-content')
  await panes.first().waitFor()
  await page.evaluate(() => { window.__diffNodes = [...document.querySelectorAll('.diff-split .cm-content')] })
  const diffSize = await size(panes.first())
  await wheel(panes.first()); await zoomed(panes.first(), diffSize)
  const diffZoomed = await size(panes.first())
  assert.equal(await size(panes.nth(1)), diffZoomed)
  assert.equal(await size(page.locator('.diff-split .cm-gutters').first()), diffZoomed)
  await wheel(panes.nth(1), 120); await zoomed(panes.nth(1), diffZoomed, -1)
  assert.equal(await page.evaluate(() => window.__diffNodes.every((node, i) => node === document.querySelectorAll('.diff-split .cm-content')[i])), true)
  assert.ok((await panes.nth(1).textContent()).includes('unsaved draft'))
  await page.locator('[data-a=dmode][data-id=unified]').click()
  const line = page.locator('.diff-unified .cl').first()
  const unified = await size(line)
  await wheel(line); await zoomed(line, unified)
  await wheel(line, 120); await zoomed(line, unified + 1, -1)
  assert.equal(await page.locator('html').evaluate((node) => node.style.getPropertyValue('--editor-size')), '14px')
  assert.equal(await page.locator('html').evaluate((node) => node.style.getPropertyValue('--fs')), '13px')
  assert.equal(fs.readFileSync(path.join(project, 'note.txt'), 'utf8'), original, 'Zooming must not save drafts')
  assert.deepEqual(errors, [])
  console.log('PASS Ctrl+wheel: source/gutter/highlight, Markdown/source switching, sandbox HTML, both split panes, unified diff, ordinary scroll, instances, drafts and undo')
} finally {
  await app.evaluate(({ dialog }) => { dialog.showMessageBoxSync = () => 1 }).catch(() => {})
  await app.close()
}
