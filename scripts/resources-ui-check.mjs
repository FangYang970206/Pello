import assert from 'node:assert/strict'
import fs from 'node:fs'
import os from 'node:os'
import path from 'node:path'
import { _electron as electron } from 'playwright'
import { zipSync, strToU8 } from 'fflate'

const data = fs.mkdtempSync(path.join(os.tmpdir(), 'awb-resources-ui-')), home = path.join(data, 'home')
for (let i = 0; i < 14; i++) {
  const folder = path.join(home, '.claude/skills', `fixture-${i}`)
  fs.mkdirSync(folder, { recursive: true })
  fs.writeFileSync(path.join(folder, 'SKILL.md'), `---\nname: fixture-${i}\ndescription: Fixture description ${i}\n---\nBody`)
}
const archive = path.join(data, 'new-skill.zip')
fs.writeFileSync(archive, zipSync({ 'new-skill/SKILL.md': strToU8('---\nname: new-skill\ndescription: Imported skill\n---\nBody') }))
fs.writeFileSync(path.join(data, 'workbench.json'), JSON.stringify({ plugins: [{ id: 'legacy', name: 'Old fake plugin' }], custom: [{ id: 'user', name: 'Custom Agent', cmd: 'node', args: '', shell: 'pwsh', letter: 'U', color: '#7fb2ff', env: [] }] }))
const env = { ...process.env, AWB_USER_DATA: data, AWB_RESOURCE_HOME: home }; delete env.ELECTRON_RUN_AS_NODE
const app = await electron.launch({ args: ['.'], env })
try {
  const page = await app.firstWindow()
  await page.click('[data-a=settings]')
  await page.click('[data-a=sec][data-id=agents]')
  await page.click('[data-a=custom][data-id=user]')
  await page.click('[data-a=ce-more]')
  await page.getByLabel('Skill 存放目录', { exact: true }).fill(path.join(home, 'custom-skills'))
  await page.getByLabel('MCP 配置文件', { exact: true }).fill(path.join(home, 'custom.json'))
  await page.click('[data-a=ce-save]')
  await page.getByRole('dialog').waitFor({ state: 'detached' })
  const targets = await page.evaluate(() => window.awb.resourceTargets())
  assert.equal(targets.find((item) => item.id === 'user').mcpPath, path.join(home, 'custom.json'))
  assert.equal(await page.getByRole('button', { name: '插件', exact: true }).count(), 0)
  await page.click('[data-a=sec][data-id=mcp]')
  assert.equal(await page.getByText('本机用户配置。添加后在对应 Agent 中重新加载或启动新会话。', { exact: true }).count(), 0, 'Resource pages should omit the redundant explanatory paragraph')
  await page.getByRole('button', { name: '添加 MCP', exact: true }).click()
  await page.getByRole('dialog', { name: '添加 MCP', exact: true }).waitFor()
  await page.getByLabel('MCP 名称', { exact: true }).fill('ui-fixture')
  await page.getByLabel('服务器配置 JSON', { exact: true }).fill('{"url":"https://example.invalid/mcp"}')
  await page.getByRole('checkbox', { name: 'Codex CLI', exact: true }).check()
  await page.getByRole('checkbox', { name: 'Custom Agent', exact: true }).check()
  await page.getByRole('button', { name: '添加到所选 Agent', exact: true }).click()
  await page.getByRole('status').filter({ hasText: 'Claude Code · 添加成功' }).waitFor()
  assert.equal(await page.getByRole('tabpanel').getByText('ui-fixture', { exact: true }).count(), 1)
  assert.equal(await page.getByRole('tabpanel').locator('small').count(), 0, 'List rows should show names only')
  const toggle = page.getByRole('switch', { name: '启用 ui-fixture', exact: true })
  await toggle.click()
  await page.waitForFunction(() => document.querySelector('[role=switch][aria-label="启用 ui-fixture"]')?.getAttribute('aria-checked') === 'false')
  await page.getByRole('button', { name: '查看 ui-fixture 详情', exact: true }).click()
  await page.getByRole('dialog', { name: 'ui-fixture', exact: true }).waitFor()
  assert.ok((await page.locator('.resource-content').textContent()).includes('https://example.invalid/mcp'))
  await page.keyboard.press('Escape')
  await page.getByRole('dialog').waitFor({ state: 'detached' })
  await toggle.click()
  await page.waitForFunction(() => document.querySelector('[role=switch][aria-label="启用 ui-fixture"]')?.getAttribute('aria-checked') === 'true')
  await page.getByRole('tab', { name: 'Codex CLI', exact: true }).click()
  await page.getByRole('tabpanel').getByText('ui-fixture', { exact: true }).waitFor()
  await page.getByRole('tab', { name: 'Pi', exact: true }).click()
  await page.getByRole('tabpanel').getByText('尚未发现 MCP', { exact: true }).waitFor()
  await page.click('[data-a=sec][data-id=skills]')
  await page.getByText('共 14 项 · 第 1 / 2 页', { exact: true }).waitFor()
  await page.getByRole('button', { name: '下一页', exact: true }).click()
  await page.getByText('共 14 项 · 第 2 / 2 页', { exact: true }).waitFor()
  assert.equal(await page.getByRole('tabpanel').locator('.resource-item').count(), 2)
  await page.getByLabel('搜索 Skill', { exact: true }).fill('fixture-13')
  await page.getByText('共 1 项 · 第 1 / 1 页', { exact: true }).waitFor()
  await page.getByRole('switch', { name: '启用 fixture-13', exact: true }).click()
  await page.waitForFunction(() => document.querySelector('[role=switch][aria-label="启用 fixture-13"]')?.getAttribute('aria-checked') === 'false')
  await page.getByRole('button', { name: '查看 fixture-13 详情', exact: true }).click()
  await page.getByRole('dialog', { name: 'fixture-13', exact: true }).waitFor()
  assert.ok((await page.locator('.resource-content').textContent()).includes('Fixture description 13'))
  await page.keyboard.press('Escape')
  await page.getByLabel('搜索 Skill', { exact: true }).fill('')
  await page.getByRole('button', { name: '添加 Skill', exact: true }).click()
  await page.getByRole('dialog', { name: '添加 Skill', exact: true }).waitFor()
  await app.evaluate(({ dialog }, archive) => { dialog.showOpenDialog = async () => ({ canceled: false, filePaths: [archive] }) }, archive)
  await page.getByRole('button', { name: '选择 ZIP 压缩包', exact: true }).click()
  await page.getByRole('checkbox', { name: 'Pi', exact: true }).check()
  await page.getByRole('button', { name: '添加到所选 Agent', exact: true }).click()
  await page.getByRole('status').filter({ hasText: 'Pi · 添加成功' }).waitFor()
  await page.getByRole('tab', { name: 'Pi', exact: true }).click()
  await page.getByRole('tabpanel').getByText('new-skill', { exact: true }).waitFor()
  assert.ok(fs.existsSync(path.join(home, '.pi/agent/skills/new-skill/SKILL.md')))
  await page.click('[data-a=sec][data-id=look]')
  await page.getByLabel('终端字体', { exact: true }).selectOption('JetBrains Mono')
  await page.getByLabel('字号', { exact: true }).selectOption('18')
  await page.getByLabel('界面字体', { exact: true }).selectOption('Segoe UI')
  await page.getByLabel('界面字号', { exact: true }).selectOption('15')
  await page.getByLabel('源码字号', { exact: true }).selectOption('17')
  const settings = (await page.evaluate(() => window.awb.getState())).db.settings
  assert.equal(settings.fontFamily, 'JetBrains Mono'); assert.equal(settings.fontSize, 18)
  assert.equal(settings.uiFontSize, 15); assert.equal(settings.editorFontSize, 17)
  assert.ok((await page.evaluate(() => getComputedStyle(document.documentElement).getPropertyValue('--mono'))).includes('JetBrains Mono'))
  console.log('PASS MCP/Skill sibling menus, per-agent listing, selected multi-agent add, ZIP picker/import, pagination/search, and legacy fake plugin removal')
  console.log('PASS modal configuration, compact lists, persisted toggles, detail dialogs, custom executor resource paths and independent font settings')
} finally { await app.close() }
