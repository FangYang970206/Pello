import assert from 'node:assert/strict'
import fs from 'node:fs'
import os from 'node:os'
import path from 'node:path'
import { execFileSync } from 'node:child_process'
import { _electron as electron } from 'playwright'

const data = fs.mkdtempSync(path.join(os.tmpdir(), 'awb-multi-repo-'))
const workspace = path.join(data, 'workspace')
const git = (cwd, ...args) => execFileSync('git', ['-C', cwd, ...args], { encoding: 'utf8', windowsHide: true })
for (const [rel, marker] of [['repo-a', 'alpha'], ['group/深层/repo-b', 'beta']]) {
  const cwd = path.join(workspace, rel)
  fs.mkdirSync(cwd, { recursive: true })
  git(cwd, 'init', '-q')
  git(cwd, 'config', 'core.autocrlf', 'false')
  fs.writeFileSync(path.join(cwd, 'shared.txt'), marker + ' original\n')
  fs.writeFileSync(path.join(cwd, '中文 空格.txt'), marker + ' unicode original\n')
  git(cwd, 'add', '.')
  git(cwd, '-c', 'user.name=Fixture', '-c', 'user.email=fixture@example.invalid', 'commit', '-qm', 'fixture')
  fs.writeFileSync(path.join(cwd, 'shared.txt'), marker + ' changed\n')
  fs.writeFileSync(path.join(cwd, '中文 空格.txt'), marker + ' unicode changed\n')
}
fs.writeFileSync(path.join(workspace, 'repo-a/new.txt'), 'new file\n')
const scoped = path.join(workspace, 'repo-a/scoped')
fs.mkdirSync(scoped)
fs.writeFileSync(path.join(scoped, 'inside.txt'), 'inside original\n')
git(path.dirname(scoped), 'add', 'scoped/inside.txt')
git(path.dirname(scoped), '-c', 'user.name=Fixture', '-c', 'user.email=fixture@example.invalid', 'commit', '-qm', 'scope fixture')
fs.writeFileSync(path.join(scoped, 'inside.txt'), 'inside changed\n')
const linked = path.join(workspace, 'linked-worktree')
git(path.join(workspace, 'repo-a'), 'worktree', 'add', '--detach', linked, 'HEAD')
fs.writeFileSync(path.join(linked, 'shared.txt'), 'linked changed\n')
fs.writeFileSync(path.join(data, 'workbench.json'), JSON.stringify({ projects: [{ id: 'multi', name: 'Multiple repositories', host: 'local', path: workspace, branch: '', agent: 'shell' }, { id: 'scope', name: 'Scoped project', host: 'local', path: scoped, branch: '', agent: 'shell' }] }))
const env = { ...process.env, AWB_USER_DATA: data }
delete env.ELECTRON_RUN_AS_NODE
const app = await electron.launch({ args: ['.'], env })
try {
  const page = await app.firstWindow()
  await page.getByRole('button', { name: '显示文件面板', exact: true }).click()
  const panel = await page.evaluate(() => window.awb.gitStatus('multi'))
  assert.equal(panel.repositories?.length, 3, 'A non-Git parent must discover repositories and Git worktrees')
  assert.ok(panel.files.some((file) => file.path === 'repo-a/shared.txt'))
  assert.ok(panel.files.some((file) => file.path === 'group/深层/repo-b/shared.txt'))
  assert.ok(panel.files.some((file) => file.path === 'group/深层/repo-b/中文 空格.txt'), 'Unicode and spaces must remain exact in Git paths')
  await page.locator('[data-repository="repo-a"]').waitFor()
  await page.getByLabel('选择仓库', { exact: true }).selectOption('repo-a')
  assert.equal(await page.locator('[data-repository]').count(), 1)
  await page.getByLabel('选择仓库', { exact: true }).selectOption('')
  assert.equal(await page.locator('[data-repository]').count(), 3)
  await page.locator('[data-a=git-view]').click()
  const scopedDirectory = page.locator('[data-repository="repo-a"] [data-a=git-dir][data-id="repo-a/scoped/"]')
  await scopedDirectory.click()
  assert.equal(await page.locator('[data-a=diff][data-id="repo-a/scoped/inside.txt"]').count(), 0)
  await scopedDirectory.click()
  await page.locator('[data-a=diff][data-id="repo-a/scoped/inside.txt"]').click()
  await page.waitForFunction(() => document.querySelector('.diff')?.textContent.includes('inside changed'))
  assert.equal(await page.locator('[data-repository="group/深层/repo-b"] [data-a=diff][data-id="group/深层/repo-b/中文 空格.txt"]').count(), 1, 'Tree retains exact paths within independent repository groups')
  await page.locator('[data-a=git-view]').click()
  const linkedDiff = await page.evaluate(() => window.awb.gitDiff('multi', 'linked-worktree/shared.txt', false))
  assert.equal(linkedDiff.before, 'alpha original\n')
  assert.equal(linkedDiff.after, 'linked changed\n')
  fs.writeFileSync(path.join(workspace, 'repo-a/large.md'), Array.from({ length: 700 }, (_, index) => `## Heading ${index + 1}\n\nOriginal paragraph ${index + 1} with enough text to exercise diff similarity.\n`).join(''))
  git(path.join(workspace, 'repo-a'), 'add', 'large.md')
  git(path.join(workspace, 'repo-a'), '-c', 'user.name=Fixture', '-c', 'user.email=fixture@example.invalid', 'commit', '-qm', 'large fixture')
  fs.writeFileSync(path.join(workspace, 'repo-a/large.md'), Array.from({ length: 701 }, (_, index) => `## Heading ${index + 1}\n\nRevised paragraph ${index + 1} with enough text to exercise diff similarity.\n`).join(''))
  const largeDiffStart = Date.now()
  await page.locator('[data-a=diff][data-id="repo-a/large.md"]').click()
  await page.locator('.diffbar .path').waitFor()
  await page.locator('.diff .cl').first().waitFor()
  const largeDiffMs = Date.now() - largeDiffStart
  assert.ok((await page.locator('.diff .cl').count()) > 1000, 'The large diff must render its rows')
  assert.ok(largeDiffMs < 5000, `A 700-line diff must not freeze the changes view: ${largeDiffMs}ms`)
  for (const [rel, marker] of [['repo-a', 'alpha'], ['group/深层/repo-b', 'beta']]) {
    const diff = await page.evaluate((rel) => window.awb.gitDiff('multi', rel + '/shared.txt', false), rel)
    assert.equal(diff.before, marker + ' original\n')
    assert.equal(diff.after, marker + ' changed\n')
  }
  const added = await page.evaluate(() => window.awb.gitDiff('multi', 'repo-a/new.txt', true))
  assert.equal(added.before, '')
  assert.equal(added.after, 'new file\n')
  await page.evaluate(() => window.awb.gitDiscard('multi', 'repo-a/shared.txt', false))
  assert.equal(fs.readFileSync(path.join(workspace, 'repo-a/shared.txt'), 'utf8'), 'alpha original\n')
  assert.equal(fs.readFileSync(path.join(workspace, 'group/深层/repo-b/shared.txt'), 'utf8'), 'beta changed\n')
  assert.equal(await page.evaluate(() => window.awb.gitDiscard('multi', '../outside.txt', false).then(() => false, () => true)), true)
  const scopedPanel = await page.evaluate(() => window.awb.gitStatus('scope'))
  assert.deepEqual(scopedPanel.files.map((file) => file.path), ['inside.txt'], 'A project inside a Git repository must stay scoped to its directory')
  const scopedDiff = await page.evaluate(() => window.awb.gitDiff('scope', 'inside.txt', false))
  assert.equal(scopedDiff.before, 'inside original\n')
  const repoA = path.join(workspace, 'repo-a')
  const repoB = path.join(workspace, 'group/深层/repo-b')
  const menu = page.getByRole('menu', { name: 'Git 变更操作' })
  const confirmation = page.locator('#modal [role=dialog]')
  const choose = async (path, action) => {
    const more = page.locator(`[data-a=git-row-more][data-id="${path}"]`)
    await more.locator('..').hover()
    await more.click()
    await menu.getByRole('menuitem', { name: action, exact: true }).click()
  }
  const confirm = async (action) => {
    await confirmation.locator('footer').getByRole('button', { name: action, exact: true }).click()
    await confirmation.waitFor({ state: 'hidden' })
  }
  git(repoA, 'add', '中文 空格.txt')
  await choose('repo-a/中文 空格.txt', '还原')
  assert.match(await confirmation.textContent(), /repo-a\/中文 空格\.txt/)
  await page.keyboard.press('Escape')
  assert.equal(fs.readFileSync(path.join(repoA, '中文 空格.txt'), 'utf8'), 'alpha unicode changed\n')
  await choose('repo-a/中文 空格.txt', '还原')
  await confirm('还原更改')
  assert.equal(fs.readFileSync(path.join(repoA, '中文 空格.txt'), 'utf8'), 'alpha unicode original\n')
  assert.equal(git(repoA, 'diff', '--cached', '--name-only'), '', 'Revert restores the index and working tree')
  assert.equal(fs.readFileSync(path.join(repoB, '中文 空格.txt'), 'utf8'), 'beta unicode changed\n')

  await page.locator('[data-a=git-view]').click()
  fs.writeFileSync(path.join(scoped, 'scratch.txt'), 'new file\n')
  await page.locator('[data-a=git-refresh]').click()
  await page.locator('[data-a=git-row-more][data-id="repo-a/scoped/scratch.txt"]').waitFor()
  await scopedDirectory.click()
  await choose('repo-a/scoped/', '还原')
  assert.match(await confirmation.textContent(), /repo-a\/scoped\/inside\.txt/)
  assert.match(await confirmation.textContent(), /repo-a\/scoped\/scratch\.txt/)
  await confirm('还原更改')
  assert.equal(fs.readFileSync(path.join(scoped, 'inside.txt'), 'utf8'), 'inside original\n')
  assert.equal(fs.existsSync(path.join(scoped, 'scratch.txt')), false, 'Folder Revert includes collapsed changes')

  const folder = '临时 [生成]'
  const folderName = 'group/深层/repo-b/' + folder + '/'
  fs.mkdirSync(path.join(repoB, folder))
  fs.writeFileSync(path.join(repoB, folder, 'sample.txt'), 'original\n')
  fs.writeFileSync(path.join(repoB, folder, 'unchanged.txt'), 'untouched\n')
  git(repoB, 'add', '--', folder)
  git(repoB, '-c', 'user.name=Fixture', '-c', 'user.email=fixture@example.invalid', 'commit', '-qm', 'folder fixture')
  fs.writeFileSync(path.join(repoB, folder, 'sample.txt'), 'ignored\n')
  fs.writeFileSync(path.join(repoB, '.gitignore'), '\uFEFF# Existing rule\r\nkeep.tmp')
  await page.locator('[data-a=git-refresh]').click()
  await choose(folderName, '忽略')
  assert.match(await confirmation.textContent(), /磁盘文件会保留/)
  await page.keyboard.press('Escape')
  assert.notEqual(git(repoB, 'ls-files', '--', folder), '', 'Cancelling Ignore leaves tracked entries intact')
  assert.equal(fs.readFileSync(path.join(repoB, '.gitignore'), 'utf8'), '\uFEFF# Existing rule\r\nkeep.tmp')
  await choose(folderName, '忽略')
  await confirm('忽略')
  const ignore = '\uFEFF# Existing rule\r\nkeep.tmp\r\n/临时 \\[生成\\]/\r\n'
  assert.equal(fs.readFileSync(path.join(repoB, '.gitignore'), 'utf8'), ignore)
  assert.equal(git(repoB, 'ls-files', '--', folder), '', 'Ignoring a folder removes all its tracked descendants from the index')
  assert.equal(fs.readFileSync(path.join(repoB, folder, 'sample.txt'), 'utf8'), 'ignored\n')
  assert.equal(fs.readFileSync(path.join(repoB, folder, 'unchanged.txt'), 'utf8'), 'untouched\n')
  assert.equal(fs.existsSync(path.join(workspace, '.gitignore')), false)
  assert.ok(git(repoB, 'check-ignore', '--', folder + '/sample.txt').trim())
  await page.evaluate((path) => window.awb.gitIgnore('multi', path, true, 'group/深层/repo-b'), folderName)
  assert.equal(fs.readFileSync(path.join(repoB, '.gitignore'), 'utf8'), ignore, 'Reapplying a rule does not duplicate it')
  await choose('group/深层/repo-b/shared.txt', '忽略')
  await confirm('忽略')
  assert.equal(git(repoB, 'ls-files', '--', 'shared.txt'), '')
  assert.equal(fs.readFileSync(path.join(repoB, 'shared.txt'), 'utf8'), 'beta changed\n')
  assert.equal(fs.readFileSync(path.join(repoB, '.gitignore'), 'utf8'), ignore + '/shared.txt\r\n')
  assert.equal(await page.evaluate(() => window.awb.gitIgnore('multi', '../outside', true, '').then(() => false, () => true)), true)
  fs.mkdirSync(path.join(scoped, 'generated'))
  fs.writeFileSync(path.join(scoped, 'generated', 'sample.txt'), 'untracked\n')
  await page.evaluate(() => window.awb.gitIgnore('scope', 'generated/', true, ''))
  assert.equal(fs.readFileSync(path.join(scoped, '.gitignore'), 'utf8'), '/generated/\n')
  assert.equal(fs.existsSync(path.join(repoA, '.gitignore')), false, 'A scoped project writes a scoped rule')

  fs.writeFileSync(path.join(scoped, 'inside.txt'), 'only in index\n')
  git(repoA, 'add', 'scoped/inside.txt')
  fs.writeFileSync(path.join(scoped, 'inside.txt'), 'only on disk\n')
  await assert.rejects(page.evaluate(() => window.awb.gitIgnore('multi', 'repo-a/scoped/inside.txt', false, 'repo-a')))
  assert.equal(git(repoA, 'show', ':scoped/inside.txt'), 'only in index\n')
  assert.equal(fs.readFileSync(path.join(scoped, 'inside.txt'), 'utf8'), 'only on disk\n')
  assert.equal(fs.existsSync(path.join(repoA, '.gitignore')), false, 'Preflight rejects untracking distinct staged content before editing .gitignore')
  await page.evaluate(() => window.awb.gitDiscard('multi', 'repo-a/scoped/inside.txt', false))


  fs.writeFileSync(path.join(repoA, 'pending-add.txt'), 'staged addition\n')
  git(repoA, 'add', 'pending-add.txt')
  git(repoA, 'mv', '中文 空格.txt', 'renamed [literal].txt')
  await page.evaluate(() => window.awb.gitDiscard('multi', 'repo-a/renamed [literal].txt', false))
  await page.evaluate(() => window.awb.gitDiscard('multi', 'repo-a/pending-add.txt', false))
  assert.equal(fs.readFileSync(path.join(repoA, '中文 空格.txt'), 'utf8'), 'alpha unicode original\n')
  assert.equal(fs.existsSync(path.join(repoA, 'renamed [literal].txt')), false)
  assert.equal(fs.existsSync(path.join(repoA, 'pending-add.txt')), false)
  assert.equal(git(repoA, 'diff', '--cached', '--name-only'), '')
  git(repoA, 'rm', '中文 空格.txt')
  fs.writeFileSync(path.join(repoA, '中文 空格.txt'), 'created after staged deletion\n')
  const recreated = await (await page.waitForFunction(async () => {
    const status = await window.awb.gitStatus('multi')
    return status.files.some((file) => file.path === 'repo-a/中文 空格.txt') ? status : false
  })).jsonValue()
  assert.equal(recreated.files.filter((file) => file.path === 'repo-a/中文 空格.txt').length, 1)
  assert.equal(recreated.untracked['repo-a/中文 空格.txt'], false)
  await page.evaluate(() => window.awb.gitDiscard('multi', 'repo-a/中文 空格.txt', false))
  assert.equal(fs.readFileSync(path.join(repoA, '中文 空格.txt'), 'utf8'), 'alpha unicode original\n')

  const deleteFolder = path.join(repoA, 'delete-dir')
  fs.mkdirSync(deleteFolder)
  fs.writeFileSync(path.join(repoA, 'delete-one.txt'), 'delete me\n')
  fs.writeFileSync(path.join(deleteFolder, 'child.txt'), 'delete directory\n')
  await page.locator('[data-a=git-refresh]').click()
  await choose('repo-a/delete-one.txt', '删除')
  await confirm('移入回收站')
  await choose('repo-a/delete-dir/', '删除')
  assert.match(await confirmation.textContent(), /包含文件夹内的全部内容/)
  await confirm('移入回收站')
  assert.equal(fs.existsSync(path.join(repoA, 'delete-one.txt')), false)
  assert.equal(fs.existsSync(deleteFolder), false)
  assert.equal(fs.existsSync(path.join(repoA, 'large.md')), true, 'Other files remain in place')

  const partial = path.join(repoA, 'partial')
  fs.mkdirSync(partial)
  for (const name of ['one.txt', 'two.txt']) fs.writeFileSync(path.join(partial, name), 'new before confirmation\n')
  await page.locator('[data-a=git-refresh]').click()
  await choose('repo-a/partial/', '还原')
  git(repoA, 'add', 'partial/two.txt')
  await confirmation.getByRole('button', { name: '还原更改', exact: true }).click()
  await page.getByRole('heading', { name: '部分文件操作失败' }).waitFor()
  assert.match(await confirmation.textContent(), /repo-a\/partial\/two\.txt/)
  assert.equal(fs.existsSync(path.join(partial, 'one.txt')), false)
  assert.equal(fs.readFileSync(path.join(partial, 'two.txt'), 'utf8'), 'new before confirmation\n', 'A newer staged file survives a stale untracked change')
  await confirmation.locator('footer').getByRole('button', { name: '关闭', exact: true }).click()
  const fresh = path.join(workspace, 'new-repository')
  fs.mkdirSync(fresh); git(fresh, 'init', '-q')
  fs.writeFileSync(path.join(fresh, 'new.txt'), 'new repository\n')
  await page.getByRole('button', { name: '重新扫描仓库', exact: true }).click()
  await page.locator('[data-repository="new-repository"]').waitFor()
  git(fresh, 'add', 'new.txt')
  await page.evaluate(() => window.awb.gitDiscard('multi', 'new-repository/new.txt', false))
  assert.equal(git(fresh, 'status', '--porcelain'), '', 'Revert removes a staged file in an unborn repository')
  fs.renameSync(path.join(linked, '.git'), path.join(linked, '.git.awb-fixture'))
  await page.evaluate(() => window.awb.gitStatus('multi'))
  const afterRemoval = await page.evaluate(() => window.awb.gitStatus('multi'))
  assert.equal(afterRemoval.errors.filter((error) => error.includes('linked-worktree')).length, 1, 'A missing repository error must not accumulate on every poll')
  console.log('PASS file and directory actions, native Revert, Delete and untracking, staged-content protection, scoped rules and nested repository failures')
} finally { await app.close() }
